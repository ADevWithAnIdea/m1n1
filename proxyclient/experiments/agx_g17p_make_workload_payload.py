"""Extract host-visible render payloads into a caller-owned workload manifest.

This treats compiler/resource pages as opaque workload input. It does not inspect
or disassemble Apple binaries; the source is an m1n1 host-visible memory snapshot.
The live builder uses these files as explicit caller BO payloads, separate from
the capture-content seeding path.
"""

import argparse
import hashlib
import importlib.util
import json
import pathlib


PAGE = 0x4000


def address_range(value):
    try:
        low, high = (int(part, 0) for part in value.split(":", 1))
    except (TypeError, ValueError):
        raise argparse.ArgumentTypeError(
            "range must be LOW:HIGH with integer addresses") from None
    if low & (PAGE - 1) or high & (PAGE - 1) or high <= low:
        raise argparse.ArgumentTypeError(
            "range must be page aligned and nonempty")
    return low, high


def load_inventory():
    path = pathlib.Path(__file__).with_name("agx_g17p_inventory_render_seed.py")
    spec = importlib.util.spec_from_file_location("g17p_inventory", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    parser.add_argument("--root", type=int, default=7,
                        help="captured UAT root index (default: 7)")
    parser.add_argument(
        "--range", dest="ranges", action="append", type=address_range,
        help="caller payload DVA range LOW:HIGH; may be repeated")
    parser.add_argument(
        "--deferred-range", dest="deferred_ranges", action="append",
        type=address_range,
        help="save caller pages for the workload to install after boot")
    args = parser.parse_args()

    inventory = load_inventory()
    snapshot = inventory.Snapshot(args.snapshot, args.root)
    # Only opaque caller/compiler payloads remain. Driver-owned roots and
    # uniform/attachment state are generated by the live builders.
    default_ranges = (
        (0x10000000000, 0x10000004000),
        (0x1000000c000, 0x10000010000),
        (0x10000048000, 0x1000004c000),
        (0x100018e8000, 0x1000195c000),
        (0x10001980000, 0x10001984000),
        (0x10001990000, 0x10001994000),
    )
    ranges = tuple(args.ranges or default_ranges)
    args.output.mkdir(parents=True, exist_ok=True)
    def extract(ranges, kind):
        entries = []
        for low, high in ranges:
            for address in range(low, high, PAGE):
                try:
                    body = snapshot.pages[address]
                except KeyError:
                    raise RuntimeError(
                        "root %d has no captured page at %#x" %
                        (args.root, address)) from None
                filename = "%014x.bin" % address
                (args.output / filename).write_bytes(body)
                entries.append({
                    "va": address,
                    "size": PAGE,
                    "path": filename,
                    "sha256": hashlib.sha256(body).hexdigest(),
                    "kind": kind,
                })
        return entries

    entries = extract(ranges, "opaque-workload-payload")
    deferred_entries = extract(
        tuple(args.deferred_ranges or ()), "caller-installed-resource")
    manifest = {
        "format": "m1n1-g17p-caller-workload-payload-v1",
        "page_size": PAGE,
        "entries": entries,
        "deferred_entries": deferred_entries,
    }
    (args.output / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print("wrote %d boot payload and %d deferred caller pages to %s" % (
        len(entries), len(deferred_entries), args.output))


if __name__ == "__main__":
    raise SystemExit(main())
