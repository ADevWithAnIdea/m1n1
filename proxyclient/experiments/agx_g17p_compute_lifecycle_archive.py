def render_mapping(backend, address, size, name, executable=False):
    """Map fresh caller-owned backing at one exact render-context DVA."""
    translated = backend.space.uat.iotranslate(
        backend.space.context, address, size)
    if any(pa is not None for pa, _length in translated):
        raise RuntimeError("%s DVA %#x is already mapped" % (name, address))
    return backend.space.alloc_at(
        address, size, name,
        AttrIndex=MemoryAttr.Shared, AP=2, nG=1,
        UXN=0 if executable else 1, OS=1,
    )


def install_channel_control_record(backend, index, words, description):
    """Publish one decoded host-owned channel-control record."""
    body = bytearray(backend.CHANNEL_CONTROL_STRIDE)
    for offset, value in words:
        struct.pack_into("<Q", body, offset, value)
    address = (
        backend.CHANNEL_CONTROL_BASE
        + int(index) * backend.CHANNEL_CONTROL_STRIDE)
    backend._write_dva(address, body)
    backend._clean_dva_range(address, len(body))
    backend.u.inst("dsb sy")
    print(
        "COMPUTE installed %s channel-control record %d at %#x" %
        (description, int(index), address),
        flush=True,
    )


def install_native_pre_cl2_channel_records(
        backend, records=NATIVE_PRE_CL2_CHANNEL_RECORD_QWORDS,
        description="native"):
    """Install and verify the coherent native pre-CL2 record array."""
    body = b"".join(
        struct.pack("<8Q", *record)
        for record in records)
    backend._write_dva(backend.CHANNEL_CONTROL_BASE, body)
    backend._clean_dva_range(backend.CHANNEL_CONTROL_BASE, len(body))
    backend.u.inst("dsb sy")
    actual = coherent_dva_sample(
        backend, backend.CHANNEL_CONTROL_BASE, len(body))
    if actual != body:
        raise RuntimeError("native pre-CL2 channel records did not read back")
    print(
        "COMPUTE installed exact %s pre-CL2 channel-control records 0-4" %
        description,
        flush=True,
    )


def initialize_channel_control_record(backend, index):
    """Publish one fresh host-owned channel-control destination record."""
    install_channel_control_record(
        backend, index, backend.CHANNEL_CONTROL_FRESH_WORDS, "fresh")


def wait_channel_control_record_transition(backend, index, timeout=0.005):
    """Wait briefly for firmware to finish activating a consumed record."""
    address = (backend.CHANNEL_CONTROL_BASE
               + int(index) * backend.CHANNEL_CONTROL_STRIDE)
    fresh = bytearray(backend.CHANNEL_CONTROL_STRIDE)
    for offset, value in backend.CHANNEL_CONTROL_FRESH_WORDS:
        struct.pack_into("<Q", fresh, offset, value)
    deadline = time.monotonic() + float(timeout)
    body = coherent_dva_sample(
        backend, address, backend.CHANNEL_CONTROL_STRIDE)
    while body == fresh and time.monotonic() < deadline:
        time.sleep(0.0001)
        body = coherent_dva_sample(
            backend, address, backend.CHANNEL_CONTROL_STRIDE)
    print(
        "COMPUTE channel-control record %d %s before contextual tick" % (
            int(index), "activated" if body != fresh else "still fresh"),
        flush=True,
    )
    return body != fresh


def firmware_object(backend, address, size, body=None):
    """Ensure an exact upper-root object exists and optionally initialize it."""
    backend._ensure_firmware_range(address, size)
    if body is not None:
        if len(body) > size:
            raise ValueError("body at %#x exceeds its allocation" % address)
        backend._write_dva(address, body)


def alias_firmware_object(backend, high, low, size):
    """Expose upper-root backing through an executable context-0 low alias."""
    firmware_object(backend, high, size)
    root = backend.firmware_high_root
    first_high = high & ~(PAGE - 1)
    first_low = low & ~(PAGE - 1)
    last_high = (high + size + PAGE - 1) & ~(PAGE - 1)
    for page in range(first_high, last_high, PAGE):
        translated = backend.space.uat.iotranslate_root(root, page, PAGE)
        if not translated or translated[0][0] is None:
            raise RuntimeError("firmware alias source %#x is unmapped" % page)
        backend.space.uat.iomap_at(
            0, first_low + page - first_high, translated[0][0], PAGE,
            AttrIndex=MemoryAttr.Shared, AP=2, nG=1, UXN=0, OS=1,
        )


def remap_firmware_page(backend, address, attr_index, uxn):
    """Retain one upper-root page's backing while replacing its leaf flags."""
    page = address & ~(PAGE - 1)
    root = backend.firmware_high_root
    translated = backend.space.uat.iotranslate_root(root, page, PAGE)
    if not translated or translated[0][0] is None:
        raise RuntimeError("firmware page %#x is unmapped" % page)
    pa = translated[0][0] & ~(PAGE - 1)
    backend.space.uat.iomap_at_root(
        root, page, pa, PAGE, ctx=backend.space.context,
        AttrIndex=attr_index, AP=1, UXN=int(uxn), OS=1)
    backend.space.uat.flush_dirty()
    backend.space.uat.invalidate_cache()
    backend.u.inst("dsb osh; tlbi vmalle1os; dsb osh; isb")


def physical_sample(backend, pa, size):
    backend.u.proxy.dc_ivac(pa, size)
    return bytes(backend.u.iface.readmem(pa, size))


def coherent_dva_sample(backend, address, size):
    """Invalidate CPU aliases, then sample one firmware-visible DVA range."""
    if backend.firmware_root == "high" and address >= 0xFFFF000000000000:
        root = backend.firmware_high_root
        ranges = backend.space.uat.iotranslate_root(root, address, size)
    else:
        ranges = backend.space.uat.iotranslate(
            backend.space.context, address, size)

    remaining = size
    for pa, span in ranges:
        if pa is None:
            raise RuntimeError("cannot sample unmapped DVA %#x" % address)
        length = min(span, remaining)
        backend.u.proxy.dc_ivac(pa, length)
        remaining -= length
        if not remaining:
            return bytes(backend._read_dva(address, size))
    raise RuntimeError(
        "translation for %#x covered %#x of %#x sample bytes" %
        (address, size - remaining, size))


class ExactColdControlTimeline:
    """Replay captured host control inputs over the proven cold-boot world."""

    def __init__(self, backend, path, first=32, last=124):
        self.backend = backend
        self.path = pathlib.Path(path)
        rows = [
            json.loads(line)
            for line in self.path.read_text().splitlines()
            if line.strip()
        ]
        # The control ring wraps later in this trace.  The target CL2 kick is
        # event 124, immediately after the first publication at slot 124, so
        # retain the first epoch instead of the last row bearing each slot.
        by_index = {}
        for row in rows:
            if "absolute_index" in row:
                by_index.setdefault(int(row["absolute_index"]), row)
        self.records = []
        for index in range(int(first), int(last) + 1):
            record = by_index.get(index)
            if record is None:
                raise RuntimeError(
                    "exact control timeline is missing absolute index %d" % index)
            if (
                int(record["producer_before"]) != index
                or int(record["producer_after"]) != index + 1
            ):
                raise RuntimeError(
                    "control timeline index %d is not a single publication" % index)
            self.records.append(record)
        self.pages = {}
        self.contexts = set()
        self.resource_spans = []
        self._prepare()

    def _context_page(self, root, address):
        page = int(address) & ~(PAGE - 1)
        key = (int(root["index"]), page)
        if key in self.pages:
            return self.pages[key]

        context = int(root["context"])
        uat = self.backend.space.uat
        if int(root.get("type", 4)) == 8:
            firmware_object(self.backend, page, PAGE)
            translated = uat.iotranslate_root(
                self.backend.firmware_high_root, page, PAGE)
        else:
            if context not in self.contexts:
                uat.set_l0(context, 0, uat.ttbr0_base, context)
                uat.set_l0(context, 1, uat.ttbr1_base, context)
                self.contexts.add(context)
            translated = uat.iotranslate(context, page, PAGE)
            if not translated or translated[0][0] is None:
                pa = self.backend.u.memalign(PAGE, PAGE)
                self.backend.u.proxy.memset32(pa, 0, PAGE)
                self.backend.u.proxy.dc_civac(pa, PAGE)
                uat.iomap_at(
                    context, page, pa, PAGE,
                    AttrIndex=MemoryAttr.Shared, AP=2, nG=1, UXN=0, OS=1,
                )
                translated = [(pa, PAGE)]
        if not translated or translated[0][0] is None:
            raise RuntimeError(
                "cannot map timeline root %d context %d DVA %#x" %
                (int(root["index"]), context, page)
            )
        self.pages[key] = int(translated[0][0]) & ~(PAGE - 1)
        return self.pages[key]

    def _write(self, root, address, body):
        cursor = 0
        while cursor < len(body):
            target = int(address) + cursor
            pa = self._context_page(root, target) + (target & (PAGE - 1))
            length = min(len(body) - cursor, PAGE - (target & (PAGE - 1)))
            self.backend.u.iface.writemem(pa, body[cursor:cursor + length])
            self.backend.u.proxy.dc_civac(pa, length)
            cursor += length

    def _ensure_zero_span(self, root, address, size):
        newly_mapped = 0
        for offset in range(0, int(size), PAGE):
            key = (int(root["index"]), (int(address) + offset) & ~(PAGE - 1))
            before = key in self.pages
            self._context_page(root, int(address) + offset)
            newly_mapped += not before
        self.resource_spans.append({
            "root": int(root["index"]),
            "address": int(address),
            "size": int(size),
            "pages": newly_mapped,
        })

    def _prepare(self):
        target_roots = {}
        for record in self.records:
            root = record.get("operand_target_root")
            if root is not None:
                target_roots[int(root["index"])] = root

        missing_spans = {}
        for record in self.records:
            table_hex = record.get("operand_table_hex")
            root = record.get("operand_table_root")
            if not table_hex or root is None:
                continue
            body = bytes.fromhex(table_hex)
            for offset in range(0, len(body), 8):
                value = struct.unpack_from("<Q", body, offset)[0]
                target = value & 0x0FFFFFFFFFFFFFFF
                if (
                    value >> 60 == 1
                    and not target & (PAGE - 1)
                    and 0x7000000000 <= target < 0x8000000000
                ):
                    missing_spans[(int(root["index"]), target)] = root
        for (_root_index, target), root in sorted(missing_spans.items()):
            self._ensure_zero_span(root, target, CONTROL_RESOURCE_BYTES)

        fields = (
            ("first_object", "first_object_root"),
            ("first_state", "first_state_root"),
            ("first_low_object", "first_low_object_root"),
            ("operand_table", "operand_table_root"),
            ("operand_target", "operand_target_root"),
        )
        for record in self.records:
            for address_name, root_name in fields:
                address = int(record.get(address_name, 0) or 0)
                root = record.get(root_name)
                if address and root is not None:
                    self._context_page(root, address)
        self.backend.space.uat.flush_dirty()
        self.backend.space.uat.invalidate_cache()
        self.backend.u.inst("dsb osh; tlbi vmalle1os; dsb osh; isb")

    def restore(self, record, restore_channel=True):
        fields = (
            ("first_object", "first_object_hex", "first_object_root"),
            ("first_state", "first_state_hex", "first_state_root"),
            ("first_low_object", "first_low_object_hex", "first_low_object_root"),
            ("operand_table", "operand_table_hex", "operand_table_root"),
            ("operand_target", "operand_target_hex", "operand_target_root"),
            ("operand_slot", "operand_slot_hex", "operand_slot_root"),
        )
        for address_name, body_name, root_name in fields:
            address = int(record.get(address_name, 0) or 0)
            body_hex = record.get(body_name)
            root = record.get(root_name)
            if address and body_hex and root is not None:
                self._write(root, address, bytes.fromhex(body_hex))
        if restore_channel:
            self.backend._write_dva(
                self.backend.CHANNEL_CONTROL_BASE,
                bytes.fromhex(record["channel_control_hex"]),
            )
            self.backend._clean_dva_range(
                self.backend.CHANNEL_CONTROL_BASE, CHANNEL_CONTROL_BYTES)
        self.backend.u.inst("dsb sy")


