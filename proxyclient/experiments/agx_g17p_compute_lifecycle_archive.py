def run_native_compute_activation_lifecycle(
        front, backend, workload, runtime,
        active_class1=None, active_class2=None,
        stop_after_trailing=False):
    """Replay the measured inactive-C2 -> active-C1 -> active-C2 lifecycle."""
    # Native has already published the context-2 queues, queue contexts, and
    # independent submission graph when class-2 control names that context.
    # Descriptors remain absent until the later work publication.
    optional_pointers = backend.muxed_queue_pointer_sets.get(1)
    if optional_pointers is None:
        raise RuntimeError("native lifecycle needs the pair-1 optional pointers")
    backend.create_muxed_queue_pair(
        3, optional_pointers, channel_pair=2)
    pair3_builder = backend.paired_builder_for(3, 1)
    if pair3_builder.leaf_pages is None:
        pair3_builder.build_submission_graph()
    backend._map_pair_status_aliases(1)
    backend.space.flush()
    backend.u.inst("dsb sy")

    # Native has context 2 installed before the class-2 transition names the
    # context-2 queue graph. A consumed control record is not sufficient: the
    # compact object must also reach its firmware-produced ready state.
    uat = backend.space.uat
    uat.set_l0(2, 0, uat.ttbr0_base, 2)
    uat.set_l0(2, 1, uat.ttbr1_base, 2)
    uat.flush_dirty()
    uat.invalidate_cache()
    backend.u.inst("dsb sy")
    backend.u.inst("tlbi aside1os, x0", 2 << 48)
    backend.u.inst("dsb sy")

    # Native publishes the fresh host-owned destination record before the
    # control that introduces the corresponding work-channel pair.  Its active
    # contents are lifecycle output and must be produced by firmware/work.
    initialize_channel_control_record(backend, 2)
    firmware_object(backend, CREATION_BASE_CLASS2, PAGE)
    firmware_object(backend, CREATION_BASE_CLASS2_STATE, PAGE)
    backend._write_dva(
        CREATION_BASE_CLASS2_STATE, compute.build_compute_shared_state())
    backend._write_dva(
        CREATION_BASE_CLASS2,
        compute.build_compute_class2_support(
            RUNTIME_OPERAND_TABLE, 0, CREATION_BASE_CLASS2_STATE,
            active=0, cursor=0xB8))
    for address in (CREATION_BASE_CLASS2, CREATION_BASE_CLASS2_STATE):
        backend._clean_dva_range(address, PAGE)
    backend.u.inst("dsb sy")
    inactive = runtime["register_compute_control"](
        2, CREATION_BASE_CLASS2, RUNTIME_OPERAND_TABLE,
        slot_offset=0x5C0, context_word=0, count=0x28,
        defer_tick=True)
    time.sleep(0.005)
    inactive_body = coherent_dva_sample(
        backend, CREATION_BASE_CLASS2, 0x68)
    inactive["object_state"] = {
        "active": struct.unpack_from("<I", inactive_body, 0x08)[0],
        "word_44": struct.unpack_from("<I", inactive_body, 0x44)[0],
        "cursor": struct.unpack_from("<I", inactive_body, 0x48)[0],
    }
    print(
        "COMPUTE inactive class-2 post-control state=%s" %
        inactive["object_state"], flush=True)
    saved_optional_ordinal = backend.forced_optional_ordinal_base
    backend.forced_optional_ordinal_base = inactive["sequence"]
    inactive_class2_renders = int(os.getenv(
        "G17P_COMPUTE_INACTIVE_CLASS2_RENDERS", "2"), 0)
    if inactive_class2_renders < 2:
        raise ValueError(
            "G17P_COMPUTE_INACTIVE_CLASS2_RENDERS must be at least two")
    try:
        if os.getenv("G17P_COMPUTE_PARTIAL_AFTER_INACTIVE_CLASS2") == "1":
            partial = run_partial_after_inactive_class2(
                front, backend, inactive)
            return {
                "inactive": inactive,
                "pair2_context": 2,
                "partial": partial,
            }
        run_render_batch(
            front, backend, workload, inactive_class2_renders,
            "native post-inactive-class2",
            queue_pair=3, channel_pair=2, descriptor_pair=3,
            descriptor_context=2, append_items=True)
    except (TimeoutError, RuntimeError):
        capture_pre_submit_state(
            backend,
            label="generated_pair3_c08f_failure",
            reference_captures=PAIR3_REFERENCE_CAPTURES)
        raise
    finally:
        backend.forced_optional_ordinal_base = saved_optional_ordinal
    inactive_tick = runtime["announce_runtime_tick"](
        inactive["sequence"], "native inactive class-2 0x2e",
        context_word=0, update_sequence=True)

    backend._write_dva(
        COMPUTE_BINDING_OPERAND_TABLE,
        compute.build_compute_operand_table_bases(
            NATIVE_CREATION_TABLE_BASES))
    backend._write_dva(
        NATIVE_CREATION_PAGE_LIST,
        compute.build_compute_operand_page_list(
            NATIVE_CREATION_TABLE_BASES[0]))
    active_class1 = active_class1 or {}
    class1_page = active_class1.get("page", CREATION_PAGE_CLASS2)
    class1_state = active_class1.get(
        "state", CREATION_PAGE_CLASS2_STATE)
    class1_operand = active_class1.get(
        "operand", COMPUTE_BINDING_OPERAND_TABLE)
    class1_low_buffer = active_class1.get(
        "low_buffer", NATIVE_CREATION_PAGE_LIST)
    class1_count = active_class1.get("count", 0x20)
    class1_active = active_class1.get("active", 1)
    class1_resource = active_class1.get("resource_class", 0x11)
    class1_cursor = active_class1.get("cursor", 0x88)
    firmware_object(backend, class1_page, PAGE)
    firmware_object(backend, class1_state, PAGE)
    backend._write_dva(
        class1_state, compute.build_compute_shared_state())
    backend._write_dva(
        class1_page,
        compute.build_compute_class1_support(
            class1_operand,
            class1_low_buffer,
            class1_state,
            active=class1_active, resource_class=class1_resource,
            cursor=class1_cursor, final_kind=2))
    for address in (
            COMPUTE_BINDING_OPERAND_TABLE, NATIVE_CREATION_PAGE_LIST,
            class1_page, class1_state):
        backend._clean_dva_range(address, PAGE)
    backend.u.inst("dsb sy")
    class1 = runtime["register_compute_control"](
        1, class1_page, class1_operand,
        slot_offset=0x440, context_word=0, count=class1_count,
        defer_tick=True)
    post_class1_renders = int(os.getenv(
        "G17P_COMPUTE_POST_CLASS1_RENDERS", "2"), 0)
    if post_class1_renders < 1:
        raise ValueError("G17P_COMPUTE_POST_CLASS1_RENDERS must be positive")
    if os.getenv("G17P_COMPUTE_RUNTIME_GRAPH_PHASE") == "post_class1":
        select_pair1_runtime_submission_graph(backend)
    exact_outer_schedule = (
        os.getenv("G17P_COMPUTE_EXACT_OUTER_SCHEDULE") == "1")
    if exact_outer_schedule:
        if post_class1_renders != len(NATIVE_POST_CLASS1_SCHEDULE):
            raise RuntimeError(
                "exact outer schedule needs %d post-class1 groups" %
                len(NATIVE_POST_CLASS1_SCHEDULE))
        for slot, node, record_a, record_b, inner_count in (
                NATIVE_POST_CLASS1_SCHEDULE):
            run_render_batch(
                front, backend, workload, 1,
                "native exact post-class1 slot %d" % slot,
                queue_pair=1, channel_pair=0, descriptor_pair=1,
                append_items=True, allow_unchanged=True,
                scheduler_node=node,
                pool_record_indices=(record_a, record_b),
                omit_optional=inner_count == 2)
    elif os.getenv("G17P_COMPUTE_RUNTIME_GRAPH_PHASE") == "post_class1":
        run_render_batch(
            front, backend, workload, 1,
            "native post-active-class1",
            queue_pair=1, channel_pair=0, descriptor_pair=1)
        if os.getenv("G17P_COMPUTE_CAPTURE_RUNTIME_GRAPH", "1") == "1":
            capture_pre_submit_state(
                backend, label="generated_runtime_graph_after_first")
        if post_class1_renders > 1:
            try:
                run_render_batch(
                    front, backend, workload, post_class1_renders - 1,
                    "native post-active-class1",
                    queue_pair=1, channel_pair=0, descriptor_pair=1)
            except (TimeoutError, RuntimeError):
                capture_pre_submit_state(
                    backend, label="generated_runtime_graph_second_failure")
                raise
    else:
        run_render_batch(
            front, backend, workload, post_class1_renders,
            "native post-active-class1",
            queue_pair=1, channel_pair=0, descriptor_pair=1)
    class1_tick = runtime["announce_runtime_tick"](
        class1["sequence"], "native active class-1 0x2e",
        context_word=1, update_sequence=True)

    active_class2 = active_class2 or {}
    active_page = active_class2.get("page", CREATION_PAGE_CLASS2)
    active_state = active_class2.get("state", CREATION_PAGE_CLASS2_STATE)
    active_operand = active_class2.get("operand", RUNTIME_OPERAND_TABLE)
    active_low_buffer = active_class2.get("low_buffer", 0)
    active_count = active_class2.get("count", 0x28)
    firmware_object(backend, active_page, PAGE)
    firmware_object(backend, active_state, PAGE)
    backend._write_dva(
        active_state, compute.build_compute_shared_state())
    backend._write_dva(
        active_page,
        compute.build_compute_class2_support(
            active_operand, active_low_buffer, active_state,
            active=1, cursor=0xB8))
    initialize_channel_control_record(backend, 3)
    backend._clean_dva_range(active_page, PAGE)
    backend._clean_dva_range(active_state, PAGE)
    backend.u.inst("dsb sy")
    channel_before = coherent_dva_sample(
        backend, backend.CHANNEL_CONTROL_BASE, 0x100)
    active = runtime["register_compute_control"](
        2, active_page, active_operand,
        slot_offset=0x5C0, context_word=1, count=active_count,
        defer_tick=True)
    run_render_batch(
        front, backend, workload, 11,
        "native post-active-class2",
        queue_pair=2, channel_pair=2, descriptor_pair=2,
        descriptor_context=2, append_items=True)
    channel_after_work = coherent_dva_sample(
        backend, backend.CHANNEL_CONTROL_BASE, 0x100)
    active_tick = runtime["announce_runtime_tick"](
        active["sequence"], "native active class-2 0x2e",
        context_word=1, update_sequence=True)
    run_render_batch(
        front, backend, workload, 1,
        "native post-class2-tick",
        queue_pair=2, channel_pair=2, descriptor_pair=2,
        descriptor_context=2, append_items=True)
    trailing_tick = runtime["announce_runtime_tick"](
        active["sequence"] + 1, "native trailing 0x2e sequence 0x20",
        context_word=1, update_sequence=True)
    if stop_after_trailing:
        channel_after_tick = coherent_dva_sample(
            backend, backend.CHANNEL_CONTROL_BASE, 0x100)
        print(
            "COMPUTE generated native activation prefix reached control "
            "slot 39",
            flush=True,
        )
        return {
            "inactive": inactive,
            "pair2_context": 2,
            "class1": class1,
            "active": active,
            "active_page": active_page,
            "remaining_ticks": [],
            "channel_changed_after_work": channel_after_work != channel_before,
            "channel_changed_after_tick": channel_after_tick != channel_before,
        }
    # Native's two registrations of the pair-2 index page are separated by a
    # complete 24-sequence interval.  The page's second registration is at
    # sequence first+0x18, even though only the first two ticks bracket the
    # pair-2 work needed by this reduced lifecycle.
    remaining_ticks = []
    interval_end = active["sequence"] + 0x18
    if os.getenv("G17P_COMPUTE_POSITIVE_CLASS2_TAIL") == "1":
        # The output-positive final-26.6 capture uses control slot 60 for a
        # class-2 registration at sequence 0x36.  Leave that slot free instead
        # of filling it with the last plain interval tick.
        interval_end -= 1
    for sequence in range(active["sequence"] + 2, interval_end):
        remaining_ticks.append(runtime["announce_runtime_tick"](
            sequence,
            "native active class-2 interval 0x2e sequence %#x" % sequence,
            context_word=1, update_sequence=True))
    channel_after_tick = coherent_dva_sample(
        backend, backend.CHANNEL_CONTROL_BASE, 0x100)
    print(
        "COMPUTE native activation controls inactive=%s tick=%s "
        "class1=%s tick=%s active=%s tick=%s trailing=%s "
        "channel-after-work=%s channel-after-tick=%s" % (
            inactive["0x20"]["consumed"], inactive_tick["consumed"],
            class1["0x20"]["consumed"], class1_tick["consumed"],
            active["0x20"]["consumed"], active_tick["consumed"],
            trailing_tick["consumed"],
            "changed" if channel_after_work != channel_before else "unchanged",
            "changed" if channel_after_tick != channel_before else "unchanged",
        ),
        flush=True,
    )
    return {
        "inactive": inactive,
        "pair2_context": 2,
        "class1": class1,
        "active": active,
        "active_page": active_page,
        "remaining_ticks": remaining_ticks,
        "channel_changed_after_work": channel_after_work != channel_before,
        "channel_changed_after_tick": channel_after_tick != channel_before,
    }


