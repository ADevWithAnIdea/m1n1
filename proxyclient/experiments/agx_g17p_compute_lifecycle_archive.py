def difference_runs(before, after):
    runs = []
    offset = 0
    while offset < len(before):
        if before[offset] == after[offset]:
            offset += 1
            continue
        end = offset + 1
        while end < len(before) and before[end] != after[end]:
            end += 1
        runs.append((offset, end))
        offset = end
    return runs


def capture_pre_submit_state(
        backend, label="generated_compute_pre_submit",
        reference_captures=None):
    """Save generated pages corresponding to the native CL_0 closure.

    Only the reference address manifest is read. Native page bytes are never
    opened or copied into the live world, so this remains a zero-capture
    execution path while producing a directly comparable diagnostic artifact.
    """
    references = tuple(reference_captures or (REFERENCE_CAPTURE,))
    addresses = set()
    for reference_capture in references:
        reference = json.loads(
            (reference_capture / "pages.json").read_text())
        addresses.update(
            int(page["dva"]) & ~(PAGE - 1)
            for page in reference["pages"])
    addresses.update({
        SHADER, RESOURCE, CDM, BUFFER_A, BUFFER_B, BUFFER_OUT,
        CLIENT_STATE, SCRATCH, CONTROL_OPERAND, CLASS2_POOL_OPERAND,
        RUNTIME_OPERAND_TABLE,
        CLASS2_POOL, CLASS2_POOL_SLOTS_HIGH, CLASS2_POOL_STATE,
        CLASS2_PREDECESSOR, CLASS2_PREDECESSOR_SLOTS,
        ROBUSTNESS,
    })
    addresses.update(
        OPERAND_BUFFER_BASE + index * compute.COMPUTE_OPERAND_BUFFER_STRIDE
        for index in range(compute.COMPUTE_OPERAND_TABLE_ENTRIES)
    )

    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    output = pathlib.Path(os.path.expanduser(
        "~/asahi_re/artifacts/agx_g17p/%s_%s" % (label, stamp)))
    output.mkdir(parents=True, exist_ok=False)
    raw = bytearray()
    pages = []
    skipped = []
    firmware_root = backend.firmware_high_root

    for address in sorted(addresses):
        page = address & ~(PAGE - 1)
        try:
            if page >= 0xFFFF000000000000:
                translated = backend.space.uat.iotranslate_root(
                    firmware_root, page, PAGE)
                translation = "firmware-high"
            elif 0x7000000000 <= page < 0x8000000000:
                translated = backend.space.uat.iotranslate(0, page, PAGE)
                translation = "context-0"
            else:
                translated = backend.space.uat.iotranslate(
                    backend.space.context, page, PAGE)
                translation = "render"
            if not translated or translated[0][0] is None:
                raise RuntimeError("unmapped")
            pa = int(translated[0][0])
            body = physical_sample(backend, pa, PAGE)
        except Exception as error:
            skipped.append({"dva": page, "error": str(error)})
            continue
        pages.append({
            "dva": page,
            "pa": pa,
            "capture_offset": len(raw),
            "translation": translation,
        })
        raw.extend(body)

    (output / "pages.bin").write_bytes(bytes(raw))
    (output / "pages.json").write_text(json.dumps({
        "format": "m1n1-t8140-g17p-generated-compute-state-v1",
        "page_size": PAGE,
        "reference_address_manifests": [
            str(reference_capture / "pages.json")
            for reference_capture in references
        ],
        "reference_bytes_read": False,
        "pages": pages,
        "skipped": skipped,
    }, indent=2, sort_keys=True) + "\n")
    print(
        "COMPUTE state snapshot=%s pages=%d skipped=%d" %
        (output, len(pages), len(skipped)),
        flush=True,
    )
    return output


def drain_staged_render(backend):
    """Physically execute and adopt the cold boot's deferred render group."""
    control_done_count = int(os.getenv(
        "G17P_BOOTSTRAP_CONTROL_DONE_COUNT", "1"), 0)
    if control_done_count < 0:
        raise ValueError(
            "G17P_BOOTSTRAP_CONTROL_DONE_COUNT must be non-negative")

    def finish_control_lifecycle():
        if backend.control_done is None:
            return
        print(
            "DRAIN sending %d bootstrap control-done message(s)" %
            control_done_count,
            flush=True,
        )
        for _ in range(control_done_count):
            backend.control_done()
            if backend.event_pump is not None:
                backend.event_pump()

    queues_before = {
        name: backend.queue_for(name)[1].indices()
        for name in ("TA_0", "3D_0")
    }
    if all(state["write"] and state["done"] == state["read"] == state["write"]
           for state in queues_before.values()):
        # Current cold boot publishes and completes this group before returning
        # to the shim.  Older versions deliberately left its doorbell pending.
        # In either case the next caller must adopt exactly one completed head,
        # never rewrite or ring it a second time.
        finish_control_lifecycle()
        backend.adopt_completed_staged_group()
        print(
            "DRAIN adopted already-completed cold-boot group queues=%s" %
            queues_before,
            flush=True,
        )
        return

    _dva, target_pa = render_mapping(
        backend, RENDER_WITNESS, PAGE, "compute_render_witness")
    before = physical_sample(backend, target_pa, 32)
    if any(before):
        raise RuntimeError("fresh render witness is not zero")

    backend.bind_color_attachment(RENDER_WITNESS, PAGE, 64, 64)
    backend.space.flush()
    backend.u.inst("dsb sy")
    backend.submitter.notify(work_doorbell_channel(0))
    time.sleep(0.005)
    after = physical_sample(backend, target_pa, 32)

    queues = {
        name: backend.queue_for(name)[1].indices()
        for name in ("TA_0", "3D_0")
    }
    print("DRAIN queues=%s witness=%s" % (
        queues, "changed" if after != before else "unchanged"), flush=True)
    if after == before:
        raise RuntimeError("cold-boot staged render did not execute")
    if all(state["done"] == state["write"] for state in queues.values()):
        finish_control_lifecycle()
    backend.adopt_completed_staged_group()


def create_pair1_render_workload(front, backend, memfd):
    """Preallocate fresh render witnesses for the complete compute lifecycle."""
    reuse_target = os.getenv("G17P_REUSE_RENDER_WITNESS") == "1"
    target_count = 1 if reuse_target else 64
    target_stride = 0x100000000
    memfd.truncate(target_count * PAGE)
    targets = []
    first_address = None
    for index in range(target_count):
        offset = index * PAGE
        if index:
            front.ctx.gobj.next_va = first_address + index * target_stride
        address = front.create_bo_from_memfd(
            memfd.fileno(), offset, PAGE, 0)
        if first_address is None:
            first_address = address
        target = front.bos[offset]
        target._no_push = True
        targets.append({"address": address, "target": target})
    print(
        "COMPUTE preallocated %d fresh render witness%s%s" % (
            target_count,
            "" if target_count == 1 else "es",
            " for legacy reuse" if reuse_target else
            " at %#x-byte DVA intervals" % target_stride,
        ),
        flush=True,
    )
    return {
        "targets": targets,
        "next_target": 0,
        "reuse_target": reuse_target,
    }


def run_pair1_render_submission(front, backend, workload, label):
    """Execute one render into a distinct freshly allocated output page."""
    target_index = (0 if workload.get("reuse_target") else
                    workload["next_target"])
    if target_index >= len(workload["targets"]):
        raise RuntimeError("compute render witness pool exhausted")
    witness = workload["targets"][target_index]
    if not workload.get("reuse_target"):
        workload["next_target"] = target_index + 1
    address = witness["address"]
    target = witness["target"]
    backend.u.proxy.memset32(target._pa, 0, PAGE)
    backend.u.proxy.dc_civac(target._pa, PAGE)
    before = physical_sample(backend, target._pa, 32)
    if any(before):
        raise RuntimeError("%s target is not fresh" % label)

    body = packed_cmdbuf(
        64, 64,
        color_attachment={"type": 0, "size": PAGE, "pointer": address},
    )
    storage = ctypes.create_string_buffer(body)
    args = types.SimpleNamespace(cmdbuf=ctypes.addressof(storage))
    result = front.submit(front.memfd, args)
    after = physical_sample(backend, target._pa, 32)
    submission = backend.last_submission
    if submission is None:
        raise RuntimeError("%s produced no submission record" % label)
    if after == before:
        raise RuntimeError("%s retired without changing its physical target" % label)
    print(
        "COMPUTE %s: result=%r ordinal=%d pair=%d item=%d target=%#x "
        "physically changed" % (
            label, result, submission["submission_ordinal"],
            submission["queue_pair"], submission["item_index"],
            address,
        ),
        flush=True,
    )
    return submission


def run_pair1_render_prelude(front, backend, memfd):
    """Execute one real created-pair render and retain its live firmware state."""
    workload = create_pair1_render_workload(front, backend, memfd)
    submission = run_pair1_render_submission(
        front, backend, workload, "pair-1 prelude")
    if submission["queue_pair"] != 1:
        raise RuntimeError(
            "pair-1 prelude selected the wrong queue pair: %r" % submission)
    workload["submission"] = submission
    return workload


def run_render_batch(
        front, backend, workload, count, label,
        queue_pair=None, channel_pair=None, descriptor_pair=None,
        descriptor_context=None, append_items=False,
        allow_unchanged=False, scheduler_node=None,
        pool_record_indices=None, omit_optional=False):
    """Run ``count`` physically verified renders without automatic controls."""
    submissions = []
    saved_registration = backend.register_runtime_pair
    saved_queue_pair = backend.forced_queue_pair
    saved_channel_pair = backend.forced_channel_pair
    saved_descriptor_pair = backend.forced_descriptor_pair
    saved_descriptor_context = backend.forced_descriptor_context
    saved_scheduler_node = backend.forced_scheduler_node
    saved_pool_record_indices = backend.forced_pool_record_indices
    saved_omit_optional = backend.omit_optional_item
    saved_reuse = backend.reuse_queue_items
    backend.register_runtime_pair = False
    backend.forced_queue_pair = queue_pair
    backend.forced_channel_pair = channel_pair
    backend.forced_descriptor_pair = descriptor_pair
    backend.forced_descriptor_context = descriptor_context
    backend.forced_scheduler_node = scheduler_node
    backend.forced_pool_record_indices = pool_record_indices
    backend.omit_optional_item = bool(omit_optional)
    if append_items:
        backend.reuse_queue_items = False
    try:
        for index in range(int(count)):
            item_label = "%s render %d/%d" % (
                label, index + 1, int(count))
            try:
                submissions.append(run_pair1_render_submission(
                    front, backend, workload, item_label))
            except RuntimeError as exc:
                if not (allow_unchanged and
                        "retired without changing its physical target" in
                        str(exc)):
                    raise
                print(
                    "COMPUTE %s: retired without pixels; retaining its "
                    "firmware lifecycle effect" % item_label,
                    flush=True,
                )
                submissions.append({"unchanged": True, "label": item_label})
    finally:
        backend.register_runtime_pair = saved_registration
        backend.forced_queue_pair = saved_queue_pair
        backend.forced_channel_pair = saved_channel_pair
        backend.forced_descriptor_pair = saved_descriptor_pair
        backend.forced_descriptor_context = saved_descriptor_context
        backend.forced_scheduler_node = saved_scheduler_node
        backend.forced_pool_record_indices = saved_pool_record_indices
        backend.omit_optional_item = saved_omit_optional
        backend.reuse_queue_items = saved_reuse
    return submissions


def run_partial_after_inactive_class2(front, backend, inactive):
    """Use the admitted context-2/pair-3 graph for our source partial pass.

    This is a transition experiment, not a captured replay.  The historical
    lifecycle above constructs and admits the graph; the modern UAPI then maps
    only the caller/compiler bundle and builds a new render command through the
    normal shim.  Keeping the hook here lets us test the partial descriptor at
    the first boundary already proven to execute ordinary source-built work.
    """
    import agx_g17p_render_uapi_partial as partial

    desired_context = 2
    occupied = set(front.g17p_fd_contexts.values())
    occupied.update(front.g17p_modern_vm_contexts.values())
    for expected in range(1, desired_context):
        if expected in occupied:
            continue
        reservation = front.modern.create_vm(
            partial.FD - 10 + expected, 0x7000000000, 0x7800000000)
        if int(reservation.token) != expected:
            raise RuntimeError(
                "partial reservation expected context %d, got %d" %
                (expected, int(reservation.token)))
        occupied.add(expected)
    vm = front.modern.create_vm(
        partial.FD, 0x7000000000, 0x7800000000)
    if int(vm.token) != desired_context:
        raise RuntimeError(
            "admitted partial expected context %d, got context %d" %
            (desired_context, int(vm.token)))

    backend.activate_execution_context(desired_context)
    partial.install_caller_graph(backend, False, fresh_pages=True)
    partial.g17p_shim.G17P_LOAD_PIPELINE_BIND_PREFIX = 0xFFFF800000000000
    front.g17p_submission_state["aux_fb"] = 0x10000300000
    front.g17p_submission_state["heapmeta"] = 0x10001B1000
    front.g17p_submission_state["tpc"] = 0x10001D8000

    os.ftruncate(front.memfd, partial.ATTACHMENT_COUNT * partial.OUTPUT_SIZE)
    outputs = []
    for index, address in enumerate(partial.OUTPUT_DVAS):
        handle = index + 1
        bo = front.modern.create_bo(
            partial.FD, handle, index * partial.OUTPUT_SIZE,
            partial.OUTPUT_SIZE)
        front.modern.bind(
            partial.FD, vm.vm_id, partial.drm_asahi_gem_bind_op(
                partial.DRM_ASAHI_BIND_READ | partial.DRM_ASAHI_BIND_WRITE,
                bo.handle, 0, partial.OUTPUT_SIZE, address))
        outputs.append(bo)
    queue = front.modern.create_queue(
        partial.FD, vm.vm_id, 1, partial.USC_EXEC_BASE)

    saved = (
        backend.register_runtime_pair,
        backend.forced_queue_pair,
        backend.forced_channel_pair,
        backend.forced_descriptor_pair,
        backend.forced_descriptor_context,
        backend.forced_optional_ordinal_base,
        backend.reuse_queue_items,
    )
    backend.register_runtime_pair = False
    backend.forced_queue_pair = 3
    backend.forced_channel_pair = 2
    backend.forced_descriptor_pair = 3
    backend.forced_descriptor_context = desired_context
    backend.forced_optional_ordinal_base = inactive["sequence"]
    backend.reuse_queue_items = False
    try:
        for bo in outputs:
            bo.token["map"][:] = bytes(partial.OUTPUT_SIZE)
        fence, commands = front.modern.submit(
            partial.FD, queue.queue_id, partial.render_commands())
        if not fence.signaled():
            raise RuntimeError("admitted partial render fence did not signal")
    finally:
        (backend.register_runtime_pair,
         backend.forced_queue_pair,
         backend.forced_channel_pair,
         backend.forced_descriptor_pair,
         backend.forced_descriptor_context,
         backend.forced_optional_ordinal_base,
         backend.reuse_queue_items) = saved

    if len(commands) != 1:
        raise RuntimeError(
            "admitted partial resolved %d commands" % len(commands))
    live_outputs = tuple(
        backend._read_dva(address, partial.OUTPUT_SIZE)
        for address in partial.OUTPUT_DVAS)
    bo_outputs = tuple(
        bytes(bo.token["map"][:partial.OUTPUT_SIZE]) for bo in outputs)
    maxima = partial.validate_outputs(bo_outputs, False)
    print(
        "COMPUTE SOURCE PARTIAL PASS sequence=%#x maxima=%r live_equal=%d "
        "queue_items=%r" % (
            inactive["sequence"], maxima,
            int(live_outputs == bo_outputs),
            dict(backend.queue_pair_submissions)),
        flush=True,
    )
    return {
        "sequence": inactive["sequence"],
        "maxima": maxima,
        "live_equal": live_outputs == bo_outputs,
    }


def prepare_native_primary_pair2_graph(backend):
    """Build the context-2 graph used for native primary-channel slots 4/5."""
    from m1n1.agx import g17p_submission as submission

    if 2 not in backend.muxed_queue_pairs:
        optional = backend.muxed_queue_pointer_sets.get(1)
        if optional is None:
            raise RuntimeError("primary pair-2 setup needs pair-1 pointers")
        backend.create_muxed_queue_pair(2, optional, channel_pair=0)

    fixed_ranges = (
        (PRIMARY_PAIR2_PRIMARY, PAGE),
        (PRIMARY_PAIR2_SECONDARY, PAGE),
        (PRIMARY_PAIR2_SHARED_SLOTS, PAGE),
        (PRIMARY_PAIR2_FLAG, PAGE),
        (PRIMARY_PAIR2_POOL_B, 0x2780),
        (PRIMARY_PAIR2_SHARED, 0x88),
        (PRIMARY_PAIR2_ZERO, 0x100),
    )
    for address, size in fixed_ranges:
        backend._ensure_firmware_range(address, size)

    leaves = submission.build_submission_leaf_pages(
        pair_index=2,
        index_group_ranges=((0x11, 6), (0x3c, 2)),
        shared_count=8,
    )
    leaf_addresses = {
        "primary_index": PRIMARY_PAIR2_PRIMARY,
        "secondary_index": PRIMARY_PAIR2_SECONDARY,
        "pool_a_slots": PRIMARY_PAIR2_POOL_A_SLOTS,
        "pool_b_slots": PRIMARY_PAIR2_POOL_B_SLOTS,
        "shared_slots": PRIMARY_PAIR2_SHARED_SLOTS,
        "flag": PRIMARY_PAIR2_FLAG,
    }
    for name in ("primary_index", "secondary_index", "shared_slots", "flag"):
        backend._write_dva(leaf_addresses[name], leaves[name])

    backend._write_dva(
        PRIMARY_PAIR2_POOL_B,
        submission.build_record_array_b(
            PRIMARY_PAIR2_POOL_B_SLOTS + submission.POOL_B_SLOT_OFFSET,
            PRIMARY_PAIR2_SHARED_SLOTS + submission.SHARED_SLOT_OFFSET,
            pair_index=2,
        ),
    )
    packed = bytearray(submission.build_shared_object((
        PRIMARY_PAIR2_PRIMARY,
        PRIMARY_PAIR2_SECONDARY,
        PRIMARY_PAIR2_SHARED_SLOTS,
        PRIMARY_PAIR2_FLAG,
    ), pair_index=2))
    struct.pack_into("<I", packed, submission.SHARED_OBJECT_PAIR_INDEX_OFFSET, 2)
    for offset, value in ((0x34, 0x20), (0x3c, 8), (0x54, 0x1f)):
        struct.pack_into("<I", packed, offset, value)
    backend._write_dva(PRIMARY_PAIR2_SHARED, packed)
    backend._write_dva(
        PRIMARY_PAIR2_ZERO, submission.build_zero_shared_object())

    builder = backend.paired_builder_for(2, 2)
    builder.leaf_pages = leaf_addresses
    builder.tiling.use_pools(PRIMARY_PAIR2_POOL_A, PRIMARY_PAIR2_POOL_B)
    builder.fragment.use_pools(PRIMARY_PAIR2_POOL_A, PRIMARY_PAIR2_POOL_B)
    builder.shared = (PRIMARY_PAIR2_SHARED, PRIMARY_PAIR2_ZERO)
    backend.space.flush()
    backend.u.inst("dsb sy")
    print(
        "COMPUTE primary pair-2 graph pools=%#x/%#x shared=%#x/%#x" % (
            PRIMARY_PAIR2_POOL_A, PRIMARY_PAIR2_POOL_B,
            PRIMARY_PAIR2_SHARED, PRIMARY_PAIR2_ZERO),
        flush=True,
    )


def run_native_render_tick_cadence(front, backend, workload, runtime):
    """Reproduce native's real-work counts at ticks 1 through 0x1c."""
    # Cold boot has already completed the initial pair-zero group, and the
    # target-verified pair-one prelude is the second native publication.
    forced_pair1_slots = {
        int(value, 0)
        for value in os.getenv(
            "G17P_COMPUTE_CADENCE_PAIR1_SLOTS", "").split(",")
        if value.strip()
    }
    exact_schedule = os.getenv("G17P_COMPUTE_EXACT_OUTER_SCHEDULE") == "1"
    schedule = {
        record[0]: record for record in NATIVE_PRIMARY_OUTER_SCHEDULE
    }
    if exact_schedule:
        prepare_native_primary_pair2_graph(backend)
    work_count = 2
    for sequence, target_count in enumerate(
            NATIVE_RENDER_COUNTS_BY_TICK, start=1):
        while work_count < target_count:
            slot = work_count
            if exact_schedule:
                (_slot, pair, node, record_a, record_b,
                 inner_count) = schedule[slot]
                run_render_batch(
                    front, backend, workload, 1,
                    "native exact slot %d before tick %#x" % (slot, sequence),
                    queue_pair=pair, channel_pair=0,
                    descriptor_pair=pair,
                    descriptor_context=2 if pair == 2 else None,
                    append_items=True, allow_unchanged=True,
                    scheduler_node=node,
                    pool_record_indices=(record_a, record_b),
                    omit_optional=inner_count == 2)
            else:
                run_render_batch(
                    front, backend, workload, 1,
                    "native cadence slot %d before tick %#x" % (slot, sequence),
                    queue_pair=1 if slot in forced_pair1_slots else None,
                    allow_unchanged=slot in forced_pair1_slots)
            work_count += 1
        if sequence == 1:
            tick = runtime["announce_runtime_tick"](
                sequence,
                "native cadence 0x2e sequence %#x" % sequence,
                context_word=0, update_sequence=True)
        else:
            tick = runtime["advance_runtime_ticks"](sequence)["final"]
        if tick is None or not tick["consumed"]:
            raise RuntimeError(
                "native cadence tick %#x was not consumed: %r" %
                (sequence, tick))
    print(
        "COMPUTE native cadence reached %d verified render pairs at tick %#x" %
        (work_count, len(NATIVE_RENDER_COUNTS_BY_TICK)),
        flush=True,
    )
    return work_count


def select_pair1_runtime_submission_graph(backend):
    """Move post-registration pair-1 work onto its registered graph."""
    graph = {
        name: address
        for name, address, _size in backend.MUX_PAIR1_GRAPH
    }
    runtime_pools = (
        graph["record_pool_a"],
        graph["record_pool_b"],
    )
    builder = backend.paired_builder_for(1)
    if builder.leaf_pages is None:
        raise RuntimeError("pair-1 runtime graph was not built by registration")
    if builder.shared is None:
        raise RuntimeError("pair-1 runtime graph has no packed/zero objects")
    builder.tiling.use_pools(*runtime_pools)
    builder.fragment.use_pools(*runtime_pools)
    backend.share_bound_record_pools = False
    backend.share_bound_submission_state = False
    if os.getenv("G17P_COMPUTE_RUNTIME_GRAPH_LOCAL_INDEX") == "1":
        base = backend.queue_pair_submissions.get(1, 0)
        backend.pair_graph_item_bases[1] = base
        print(
            "COMPUTE pair-1 runtime graph restarts local items at "
            "transport item %d" % base,
            flush=True,
        )
    if os.getenv("G17P_COMPUTE_RUNTIME_GRAPH_COUNTER_HISTORY") == "1":
        count = backend.queue_pair_submissions.get(1, 0)
        packed = builder.shared[0]
        backend._write_dva(
            packed,
            struct.pack("<IIII", count, count, 1, 1),
        )
        backend._write_dva(packed + 0x14, struct.pack("<I", count))
        backend._clean_dva_range(packed, 0x18)
        backend.u.inst("dsb sy")
        print(
            "COMPUTE pair-1 runtime packed progress seeded to %d" % count,
            flush=True,
        )
    print(
        "COMPUTE pair-1 post-registration graph pools=%#x/%#x "
        "shared=%#x/%#x" % (runtime_pools + tuple(builder.shared)),
        flush=True,
    )
    return {"pools": runtime_pools, "shared": tuple(builder.shared)}


