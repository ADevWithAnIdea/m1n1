def diagnose(backend, entry, queue, graph, objects, before_buffers,
             before_diagnostics):
    """Print bounded live state without mistaking retirement for execution."""
    print("COMPUTE queue=%s channel=%s" % (
        queue.indices(), backend.channels.counters(entry)), flush=True)
    for label, address, size in (
        ("job_list", graph["job_list"], g17p.JOB_LIST_SIZE),
        ("scheduler", graph["scheduler"], 0x100),
        ("scheduler_slot", graph["scheduler_slot"], 8),
        ("shared_support", SHARED_SUPPORT, 0x80),
    ):
        body = backend._read_dva(address, size)
        nonzero = [
            "+%#x=%#x" % (offset, struct.unpack_from("<Q", body, offset)[0])
            for offset in range(0, size & ~7, 8)
            if struct.unpack_from("<Q", body, offset)[0]
        ]
        print("COMPUTE %s: %s" % (label, " ".join(nonzero)), flush=True)
    for label, address, size in diagnostic_ranges(graph):
        before = before_diagnostics[label]
        after = coherent_dva_sample(backend, address, size)
        runs = difference_runs(before, after)
        if not runs:
            print("COMPUTE watch %-14s unchanged" % label, flush=True)
            continue
        details = []
        for start, end in runs[:12]:
            excerpt_end = min(end, start + 16)
            details.append(
                "+%#x..+%#x:%s->%s" %
                (start, end, before[start:excerpt_end].hex(),
                 after[start:excerpt_end].hex()))
        if len(runs) > 12:
            details.append("...%d more" % (len(runs) - 12))
        print("COMPUTE watch %-14s changed %s" %
              (label, " ".join(details)), flush=True)
    for name in ("compute_a", "compute_b", "compute_out"):
        after = physical_sample(backend, objects[name][1], 64 * 4)
        print("COMPUTE %-11s %s" %
              (name, "changed" if after != before_buffers[name] else "unchanged"),
              flush=True)


def report_diagnostic_changes(backend, graph, before_diagnostics, prefix):
    """Report bounded object changes around a control-only experiment."""
    for label, address, size in diagnostic_ranges(graph):
        before = before_diagnostics[label]
        after = coherent_dva_sample(backend, address, size)
        runs = difference_runs(before, after)
        if not runs:
            print("%s %-20s unchanged" % (prefix, label), flush=True)
            continue
        details = []
        for start, end in runs[:16]:
            excerpt_end = min(end, start + 16)
            details.append(
                "+%#x..+%#x:%s->%s" %
                (start, end, before[start:excerpt_end].hex(),
                 after[start:excerpt_end].hex()))
        if len(runs) > 16:
            details.append("...%d more" % (len(runs) - 16))
        print("%s %-20s changed %s" %
              (prefix, label, " ".join(details)), flush=True)


def reset_compute_scheduler_heads(backend, base):
    """Restore the four native empty scheduler heads before first CL work."""
    for index in range(4):
        address = base + index * g17p.JOB_LIST_SIZE
        backend._write_dva(address, g17p.build_job_list(address))
        backend._clean_dva_range(address, g17p.JOB_LIST_SIZE)
    backend.u.inst("dsb sy")

    for index in range(4):
        address = base + index * g17p.JOB_LIST_SIZE
        head = g17p.parse_job_list(
            backend._read_dva(address, g17p.JOB_LIST_SIZE),
            own_address=address,
        )
        if not head.get("empty"):
            raise RuntimeError(
                "compute scheduler head %#x did not reset: %r" %
                (address, head))
    print("COMPUTE reset four scheduler heads at %#x" % base, flush=True)


def run_exact_native_cl2_tail(front, backend, runtime, workload):
    """Publish the byte-exact output-positive native CL2 graph.

    The long generated lifecycle above supplies the control history.  This
    tail deliberately imports the compact CL2 experiment only after that
    history has completed so its fixed environment cannot alter cold boot.
    """
    import agx_g17p_compute as exact

    native_client = os.getenv("G17P_COMPUTE_NATIVE_CLIENT_REPLAY") == "1"
    native = None
    if native_client:
        native = exact.install_native_client_context(backend)
        descriptor = native["descriptor"]
        terminator = struct.unpack_from("<Q", descriptor, 0xEE0)[0]
        objects = {"output": (native["output_dva"], native["output_pa"])}
        expected = native["expected_output"]
        exact_client_space = native["space"]
        # The long render lifecycle does not build compute's sparse 0x700...
        # operand namespace.  Construct it before replaying the native client
        # closure so the later class-1 extents reuse complete tranches rather
        # than colliding with a few inherited pages.
        exact.map_operand_pages(backend, exact_client_space)
    else:
        objects, expected, terminator, exact_client_space = (
            exact.build_client_graph(backend))

    # Keep two output-positive pair-2 publications from the proven lifecycle,
    # but do not add the unrelated second class-2 registration from another
    # capture.  The authoritative CL2 control ring contains only ticks between
    # the initial c0908 registration at sequence 0x32 and its 0x5a reuse.
    run_render_batch(
        front, backend, workload, 2,
        "native pre-CL2 cadence",
        queue_pair=2, channel_pair=2, descriptor_pair=2,
        descriptor_context=2, append_items=True)

    # Map every object named by the complete pre-kick snapshot, but use the
    # snapshot's compact bytes only as a final-state oracle.
    exact.prepare_native_pre_cl2_control_objects(
        backend, exact_client_space)
    current_class2_tail = (
        os.getenv("G17P_COMPUTE_CURRENT_CLASS2_TAIL") == "1")
    positive_class2_tail = (
        os.getenv("G17P_COMPUTE_POSITIVE_CLASS2_TAIL") == "1")
    if current_class2_tail and positive_class2_tail:
        raise RuntimeError("compute class-2 tail modes are mutually exclusive")
    if positive_class2_tail:
        advanced = {
            "first": None,
            "last": 0x35,
            "count": 0,
            "restart": None,
            "final": None,
        }
    else:
        advanced = runtime["advance_runtime_ticks"](
            0x8E if current_class2_tail else 0x59)
    print("COMPUTE advanced to native suffix: %s" % advanced, flush=True)

    class1_initial = None
    class1_initial_tick = None
    class1_initial_trailing = None
    class1_final = None
    class1_final_tick = None
    class2_tick = None
    class2_trailing = None
    class2_second_trailing = None

    if not current_class2_tail and not positive_class2_tail:
        state1_before = struct.unpack_from(
            "<Q", coherent_dva_sample(
                backend, exact.NATIVE_CLASS1_STATE, 8), 0)[0]
        first_class1 = compute.build_compute_class1_support(
            exact.NATIVE_CLASS1_OPERAND, exact.NATIVE_CLASS1_PAGE_LIST,
            exact.NATIVE_CLASS1_STATE,
            active=0, resource_class=0x11, cursor=0x88, final_kind=2)
        backend._write_dva(exact.NATIVE_CLASS1_SUPPORT, first_class1)
        backend._clean_dva_range(exact.NATIVE_CLASS1_SUPPORT, PAGE)
        backend.u.inst("dsb sy")
        class1_initial = runtime["register_compute_control"](
            1, exact.NATIVE_CLASS1_SUPPORT, exact.NATIVE_CLASS1_OPERAND,
            slot_offset=0x440, context_word=0, count=0x28,
            defer_tick=True)
        class1_initial_tick = runtime["announce_runtime_tick"](
            class1_initial["sequence"], "native c0908 initial 0x2e",
            context_word=0, update_sequence=True)
        class1_initial_trailing = runtime["announce_runtime_tick"](
            class1_initial["sequence"] + 1,
            "native c0908 initial trailing 0x2e",
            context_word=0, update_sequence=True)

    if positive_class2_tail:
        positive_low = 0x7001F00000
        positive_operand = 0x7002108000
        positive_span = positive_operand - positive_low
        if native_client:
            # Context 3 is cloned after the generated activation lifecycle, so
            # it inherits one page at each end of this range.  The final-26.6
            # class-2 object reuses those addresses as one complete low extent.
            # Activation has retired at this boundary; replace only its sparse
            # aliases before constructing the observed final extent.
            positive_total = (
                positive_span + exact.NATIVE_CONTROL_OPERAND_SIZE)
            positive_end = positive_low + positive_total
            owners = []
            for obj in exact_client_space.objects:
                obj_address = int(obj.get("map_va", obj["va"]))
                obj_size = int(obj.get("map_size", obj["size"]))
                if (positive_low < obj_address + obj_size
                        and obj_address < positive_end):
                    owners.append(obj)
            if owners:
                raise RuntimeError(
                    "positive class-2 replacement overlaps owned objects: %s"
                    % ", ".join(obj["name"] for obj in owners))
            removed = exact_client_space.uat.iounmap(
                exact_client_space.context, positive_low, positive_total)
            exact_client_space.uat.flush_dirty()
            exact_client_space.uat.invalidate_cache()
            backend.u.inst("dsb sy")
            backend.u.inst("tlbi aside1os, x0", 3 << 48)
            backend.u.inst("dsb sy")
            print(
                "COMPUTE replaced %#x bytes of sparse retired activation "
                "mappings across %#x+%#x" %
                (removed, positive_low, positive_total),
                flush=True,
            )
        _low_dva, low_pa = exact.map_client(
            backend, positive_low, positive_span,
            "positive_class2_low_registration", reuse=True,
            space=exact_client_space)
        _operand_dva, operand_pa = exact.map_client(
            backend, positive_operand, exact.NATIVE_CONTROL_OPERAND_SIZE,
            "positive_class2_operand", reuse=True,
            space=exact_client_space)
        backend.u.proxy.memset32(low_pa, 0, positive_span)
        backend.u.iface.writemem(
            low_pa,
            compute.build_compute_operand_page_lists(
                exact.OPERAND_BUFFER_BASE))
        backend.u.proxy.memset32(
            operand_pa, 0, exact.NATIVE_CONTROL_OPERAND_SIZE)
        backend.u.iface.writemem(
            operand_pa,
            compute.build_compute_operand_table(exact.OPERAND_BUFFER_BASE))
        backend.u.proxy.dc_civac(low_pa, positive_span)
        backend.u.proxy.dc_civac(
            operand_pa, exact.NATIVE_CONTROL_OPERAND_SIZE)
        exact_client_space.flush()
        backend.u.inst("dsb sy")
        backend.u.inst("tlbi aside1os, x0", 3 << 48)
        backend.u.inst("dsb sy")

        positive_state = bytearray(PAGE)
        struct.pack_into("<Q", positive_state, 0, 0x18)
        class2_support = compute.build_compute_class2_support(
            positive_operand, positive_low, exact.NATIVE_CLASS2_STATE,
            active=0, cursor=0xE0, final_kind=3,
            word_20=0x0000319800001598,
            word_28=0x00001C0000000000,
            field_54=0x18)
        class2_operand = positive_operand
        class2_context = 0
        class2_count = 0x28
        class2_state = bytes(positive_state)
    else:
        class2_support = compute.build_compute_class2_support(
            exact.NATIVE_CLASS2_OPERAND,
            0 if current_class2_tail else exact.NATIVE_CLASS2_PAGE_LIST,
            exact.NATIVE_CLASS2_STATE,
            active=1, resource_class=0x17, cursor=0xB8,
            final_kind=3)
        class2_operand = exact.NATIVE_CLASS2_OPERAND
        class2_context = 1
        class2_count = 0x18
        class2_state = compute.build_compute_shared_state()
    backend._write_dva(exact.NATIVE_CLASS2_STATE, class2_state)
    backend._write_dva(exact.NATIVE_CLASS2_SUPPORT, class2_support)
    backend._clean_dva_range(exact.NATIVE_CLASS2_STATE, PAGE)
    backend._clean_dva_range(exact.NATIVE_CLASS2_SUPPORT, PAGE)
    backend.u.inst("dsb sy")
    class2 = runtime["register_compute_class2"](
        exact.NATIVE_CLASS2_SUPPORT, class2_operand,
        slot_offset=0x5C0, context_word=class2_context,
        count=class2_count,
        defer_tick=True)
    if positive_class2_tail:
        if class2["sequence"] != 0x36 or class2["0x20"]["slot"] != 60:
            raise RuntimeError(
                "positive class-2 registration missed native slot: %r" %
                class2)
        class2_tick = runtime["announce_runtime_tick"](
            0x36, "positive native class-2 0x2e",
            context_word=0, update_sequence=True)
        class2_trailing = runtime["announce_runtime_tick"](
            0x37, "positive native class-2 trailing 0x2e",
            context_word=0, update_sequence=True)
        final_sequence = 0x37
        post_compute_context = None
        print(
            "COMPUTE output-positive class-2 suffix consumed at slots "
            "60-62; CL2 follows tick 0x37",
            flush=True,
        )
    elif current_class2_tail:
        final_sequence = class2["sequence"] - 1
        post_compute_context = 0
        print(
            "COMPUTE current native class-2 consumed; sequence=%#x, "
            "low pointer zero, CL2 must precede its 0x2e" %
            class2["sequence"],
            flush=True,
        )
    else:
        class2_tick = runtime["announce_runtime_tick"](
            class2["sequence"], "native c095 0x2e",
            context_word=1, update_sequence=True)
        class2_trailing = runtime["announce_runtime_tick"](
            class2["sequence"] + 1, "native c095 trailing 0x2e",
            context_word=1, update_sequence=True)
        class2_second_trailing = runtime["announce_runtime_tick"](
            class2["sequence"] + 2, "native c095 second trailing 0x2e",
            context_word=1, update_sequence=True)

        # The later class-1 input retains the firmware-owned state count.
        state1_pre_final = struct.unpack_from(
            "<Q", coherent_dva_sample(
                backend, exact.NATIVE_CLASS1_STATE, 8), 0)[0]
        final_class1_input = compute.build_compute_class1_support(
            exact.NATIVE_CLASS1_OPERAND, exact.NATIVE_CLASS1_PAGE_LIST,
            exact.NATIVE_CLASS1_STATE,
            active=0, cursor=0xB0, final_kind=2,
            word_20=0x0000352000001820,
            word_28=0x00001D0000000000,
            field_54=max(0, state1_pre_final - 1))
        backend._write_dva(
            exact.NATIVE_CLASS1_SUPPORT, final_class1_input)
        backend._clean_dva_range(exact.NATIVE_CLASS1_SUPPORT, PAGE)
        backend.u.inst("dsb sy")
        class1_final = runtime["register_compute_control"](
            1, exact.NATIVE_CLASS1_SUPPORT, exact.NATIVE_CLASS1_OPERAND,
            slot_offset=0x580, context_word=0, count=0x38,
            defer_tick=True)
        class1_final_tick = runtime["announce_runtime_tick"](
            class1_final["sequence"], "native c0908 final 0x2e",
            context_word=0, update_sequence=True)
        suffix_ticks = runtime["advance_runtime_ticks"](0x65)
        final_sequence = 0x65
        post_compute_context = 2

        expected_controls = exact.build_native_pre_cl2_control_objects()
        produced_controls = {
            "class1": coherent_dva_sample(
                backend, exact.NATIVE_CLASS1_SUPPORT, PAGE),
            "class1_state": coherent_dva_sample(
                backend, exact.NATIVE_CLASS1_STATE, PAGE),
            "class2": coherent_dva_sample(
                backend, exact.NATIVE_CLASS2_SUPPORT, PAGE),
            "class2_state": coherent_dva_sample(
                backend, exact.NATIVE_CLASS2_STATE, PAGE),
        }
        control_differences = {
            name: sum(left != right for left, right in zip(
                produced_controls[name], expected_controls[name]))
            for name in produced_controls
        }
        print(
            "COMPUTE native suffix consumed; state1 %#x -> %#x, "
            "final differences=%s, sequence=%#x ticks=%s" % (
                state1_before, state1_pre_final, control_differences,
                final_sequence, suffix_ticks),
            flush=True,
        )

    channel_records = coherent_dva_sample(
        backend, backend.CHANNEL_CONTROL_BASE,
        backend.CHANNEL_CONTROL_STRIDE * 5)
    for index in range(5):
        start = index * backend.CHANNEL_CONTROL_STRIDE
        record = channel_records[
            start:start + backend.CHANNEL_CONTROL_STRIDE]
        print(
            "COMPUTE pre-CL2 channel-control record %d: %s" %
            (index, record.hex()),
            flush=True,
        )
    if os.getenv("G17P_COMPUTE_EXACT_NATIVE_CHANNEL") == "1":
        if positive_class2_tail:
            install_native_pre_cl2_channel_records(
                backend, POSITIVE_PRE_CL2_CHANNEL_RECORD_QWORDS,
                "output-positive final-26.6")
        else:
            install_native_pre_cl2_channel_records(backend)

    # Native has both complete primary scheduler-history pages in place at
    # this boundary, immediately before the output-positive CL2 publication.
    # Keep the proven render lifecycle untouched, then require the generated
    # high/context-0 aliases to contain those exact structured records.
    exact.install_native_compute_primary_records(backend)

    native_final_descriptor = (
        native_client
        and os.getenv("G17P_COMPUTE_NATIVE_FINAL_DESCRIPTOR") == "1")
    native_registers = None
    if native_final_descriptor:
        profile = exact.OUTPUT_POSITIVE_FINAL_26_6_PROFILE
        native_registers = exact.compute_registers(
            profile["dispatch_identity"], profile["register_gate"],
            resource=exact.NATIVE_RESOURCE,
            cdm=exact.NATIVE_CDM,
            robustness=native["output_dva"],
        )
    queue = exact.build_firmware_graph(
        backend, terminator, reuse_scheduler_lifecycle=False,
        descriptor_override=(
            descriptor
            if native_client and not native_final_descriptor else None),
        submission_profile=(
            exact.OUTPUT_POSITIVE_FINAL_26_6_PROFILE
            if positive_class2_tail
            and (not native_client or native_final_descriptor) else None),
        registers_override=native_registers)

    # Native output-positive CL2 descriptors select a distinct context-3 low
    # root.  The generated path builds that root independently; only the
    # firmware high root is shared.
    uat = exact_client_space.uat
    for label, address in (
            ("shader", exact.NATIVE_SHADER if native_client else exact.SHADER),
            ("resource", exact.NATIVE_RESOURCE if native_client
             else exact.RESOURCE),
            ("cdm", exact.NATIVE_CDM if native_client else exact.CDM),
            ("output", native["output_dva"] if native_client
             else exact.BUFFER_OUT)):
        translated = uat.iotranslate(3, address, 1)
        if not translated or translated[0][0] is None:
            raise RuntimeError(
                "exact CL2 context 3 does not map %s at %#x" %
                (label, address))
        print(
            "COMPUTE exact CL2 context3 %s=%#x -> pa=%#x" %
            (label, address, translated[0][0]),
            flush=True,
        )

    entry = backend.channels.by_name("CL_2")
    if entry is None:
        raise RuntimeError("generated lifecycle exposes no CL_2 channel")
    published = backend.submitter.stage(
        entry, queue,
        (exact.DESCRIPTOR, exact.OPTIONAL, exact.EVENT),
        group_number=1, slot=0, first_submit=True,
        kind="compute", announce=False,
    )
    for address, size in (
            (exact.ITEM_RING, 0x18),
            (exact.QUEUE_POINTERS, 0x80),
            (entry["ring_addr"], g17p.RING_SLOT_SIZE)):
        backend._clean_dva_range(address, size)
    for address in entry["state_addrs"]:
        backend._clean_dva_range(address, 4)
    backend.u.inst("dsb sy")

    if os.getenv("G17P_COMPUTE_SKIP_EXACT_CL2_AUDIT") != "1":
        exact.audit_exact_cl2_pointer_closure(backend, entry, queue)
    else:
        print("COMPUTE skipping read-only CL2 pointer audit", flush=True)
    if native_client:
        native["restore_displaced_logical_slot"]()

    output_pa = objects["output"][1]
    output_size = PAGE if native_client else 64 * 4
    before = exact.physical_read(backend, output_pa, output_size)
    print(
        "COMPUTE exact native CL2 publishing grid %d context 3; "
        "queue=%s channel=%s class2=%s" % (
            queue.grid_index, queue.indices(),
            backend.channels.counters(entry),
            {"class1_initial": class1_initial,
             "class1_initial_tick": class1_initial_tick,
             "class1_initial_trailing": class1_initial_trailing,
             "class2": class2, "class2_tick": class2_tick,
             "class2_trailing": class2_trailing,
             "class2_second_trailing": class2_second_trailing,
             "class1_final": class1_final,
             "class1_final_tick": class1_final_tick}),
        flush=True,
    )
    exact.trigger_submission(front, backend, "work", "CL_2")

    after = before
    deadline = time.monotonic() + 0.010
    while time.monotonic() < deadline:
        after = exact.physical_read(backend, output_pa, output_size)
        if after != before:
            break
        time.sleep(0.0001)
    print(
        "COMPUTE exact native CL2 before tick queue=%s channel=%s output=%s" % (
            queue.indices(), backend.channels.counters(entry),
            "changed" if after != before else "unchanged"),
        flush=True,
    )

    if post_compute_context is not None:
        class2_tick = runtime["announce_runtime_tick"](
            final_sequence + 1,
            "exact native CL2 post-compute 0x2e",
            context_word=post_compute_context, update_sequence=True,
        )
        deadline = time.monotonic() + 0.010
        while after == before and time.monotonic() < deadline:
            after = exact.physical_read(backend, output_pa, output_size)
            if after != before:
                break
            time.sleep(0.0001)
        print(
            "COMPUTE exact native CL2 after tick queue=%s channel=%s "
            "tick=%s output=%s" % (
                queue.indices(), backend.channels.counters(entry), class2_tick,
                "changed" if after != before else "unchanged"),
            flush=True,
        )

    if after == before:
        print("COMPUTE OUTPUT: unchanged", flush=True)
        return 2
    if native_client:
        changed = sum(left != right for left, right in zip(before, after))
        if after != expected:
            print(
                "COMPUTE OUTPUT: NOT EXECUTED, native client page changed "
                "%d bytes but does not match the known t256 post-write image" %
                changed,
                flush=True,
            )
            return 3
        print(
            "COMPUTE OUTPUT: EXECUTED, native client page changed %d bytes; "
            "captured-post-image=match" % changed,
            flush=True,
        )
        return 0
    actual = list(struct.unpack("<64f", after))
    if actual != expected:
        mismatch = next(
            index for index, values in enumerate(zip(actual, expected))
            if values[0] != values[1])
        print(
            "COMPUTE OUTPUT: changed but wrong at %d: got %r expected %r" %
            (mismatch, actual[mismatch], expected[mismatch]),
            flush=True,
        )
        return 3
    print("COMPUTE OUTPUT: EXECUTED, 64/64 exact add3 results", flush=True)
    return 0


