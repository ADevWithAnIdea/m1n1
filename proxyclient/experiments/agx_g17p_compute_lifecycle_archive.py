def build_client_objects(backend):
    """Allocate and initialize every object reached through context 1."""
    objects = {}
    for address, size, name, executable in (
        (RESOURCE, RESOURCE_SIZE, "compute_resource", False),
        (CDM, PAGE, "compute_cdm", False),
        (BUFFER_A, PAGE, "compute_a", False),
        (BUFFER_B, PAGE, "compute_b", False),
        (BUFFER_OUT, PAGE, "compute_out", False),
        (SHADER, PAGE, "compute_shader", True),
        (SCRATCH, 0x10000, "compute_scratch", False),
        (ROBUSTNESS, PAGE, "compute_robustness", False),
        (CLIENT_STATE, PAGE, "compute_client_state", False),
        (CONTROL_OPERAND, PAGE, "compute_control_operand", False),
        (CLASS2_POOL_OPERAND, PAGE, "compute_class2_pool_operand", False),
        (CREATION_CLASS1_OPERAND_TABLE, PAGE,
         "compute_creation_class1_operand_table", False),
    ):
        objects[name] = render_mapping(
            backend, address, size, name, executable=executable)

    for index, address in enumerate(CREATION_EXTRA_OPERAND_BASES):
        name = "compute_creation_extra_operand_%d" % index
        objects[name] = render_mapping(
            backend, address, compute.COMPUTE_OPERAND_BUFFER_SIZE, name)

    for index in range(compute.COMPUTE_OPERAND_TABLE_ENTRIES):
        address = (OPERAND_BUFFER_BASE
                   + index * compute.COMPUTE_OPERAND_BUFFER_STRIDE)
        name = "compute_operand_%02d" % index
        objects[name] = render_mapping(backend, address, PAGE, name)

    values_a = [1000.0 + index * 0.5 for index in range(64)]
    values_b = [1100.0 + index * 0.5 for index in range(64)]
    expected = [left + right for left, right in zip(values_a, values_b)]
    backend.space.write(objects["compute_a"][1], struct.pack("<64f", *values_a))
    backend.space.write(objects["compute_b"][1], struct.pack("<64f", *values_b))
    backend.space.write(objects["compute_shader"][1], ADD3_SHADER)
    backend.space.write(
        objects["compute_client_state"][1],
        compute.build_compute_operand_table(OPERAND_BUFFER_BASE),
    )
    backend.space.write(objects["compute_control_operand"][1], bytes(PAGE))
    backend.space.write(objects["compute_class2_pool_operand"][1], bytes(PAGE))

    resource = compute.build_buffer_resource_table(
        (BUFFER_A, BUFFER_B, BUFFER_OUT), size=RESOURCE_SIZE)
    stream = compute.build_cdm_stream((
        compute.build_direct_dispatch(
            SHADER, grid=(64, 1, 1), threadgroup=(32, 1, 1)),
    ))
    backend.space.write(objects["compute_resource"][1], resource)
    backend.space.write(objects["compute_cdm"][1], stream)
    return objects, expected, len(stream) - 4


