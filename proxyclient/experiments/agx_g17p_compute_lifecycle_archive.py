def run_exact_timeline_cl2_submit(front, backend):
    """Submit the captured output-positive CL2 after exact controls 32..124."""
    import agx_g17p_compute as exact

    native = exact.install_native_client_context(backend)
    descriptor = native["descriptor"]
    terminator = struct.unpack_from("<Q", descriptor, 0xEE0)[0]

    # The scheduler-history records are host inputs at this boundary.  Give
    # each one explicit high and low mappings before constructing its bytes.
    for address in (
            exact.PRIMARY_RECORD_PREDECESSOR,
            exact.PRIMARY_RECORD_SENTINEL,
            exact.PRIMARY_RECORD_A_HIGH,
            exact.PRIMARY_RECORD_B_HIGH):
        exact.map_firmware(backend, address, PAGE)
    exact.alias_firmware(
        backend, exact.PRIMARY_RECORD_A_HIGH,
        exact.PRIMARY_RECORD_A_LOW, PAGE)
    exact.alias_firmware(
        backend, exact.PRIMARY_RECORD_B_HIGH,
        exact.PRIMARY_RECORD_B_LOW, PAGE)
    backend.space.flush()
    backend.u.inst("dsb osh; tlbi vmalle1os; dsb osh; isb")
    exact.install_native_compute_primary_records(backend)

    queue = exact.build_firmware_graph(
        backend, terminator, reuse_scheduler_lifecycle=False,
        descriptor_override=descriptor)

    uat = native["space"].uat
    for label, address in (
            ("shader", exact.NATIVE_SHADER),
            ("resource", exact.NATIVE_RESOURCE),
            ("cdm", exact.NATIVE_CDM),
            ("output", native["output_dva"])):
        translated = uat.iotranslate(3, address, 1)
        if not translated or translated[0][0] is None:
            raise RuntimeError(
                "exact timeline CL2 context 3 does not map %s at %#x" %
                (label, address))
        print(
            "COMPUTE exact timeline CL2 context3 %s=%#x -> pa=%#x" %
            (label, address, translated[0][0]),
            flush=True,
        )

    entry = backend.channels.by_name("CL_2")
    if entry is None:
        raise RuntimeError("exact timeline exposes no CL_2 channel")
    published = backend.submitter.stage(
        entry, queue,
        (exact.DESCRIPTOR, exact.OPTIONAL, exact.EVENT),
        group_number=1, slot=0, first_submit=True,
        kind="compute", announce=False,
    )
    for address, size in (
            (exact.ITEM_RING, 0x18),
            (exact.QUEUE_POINTERS, 0x80),
            (entry["ring_addr"], g17p.RING_SLOT_SIZE)):
        backend._clean_dva_range(address, size)
    for address in entry["state_addrs"]:
        backend._clean_dva_range(address, 4)
    backend.u.inst("dsb sy")
    if os.getenv("G17P_COMPUTE_SKIP_EXACT_CL2_AUDIT") != "1":
        exact.audit_exact_cl2_pointer_closure(backend, entry, queue)
    else:
        print("COMPUTE skipping read-only CL2 pointer audit", flush=True)
    if native_client:
        native["restore_displaced_logical_slot"]()

    output_pa = native["output_pa"]
    before = exact.physical_read(backend, output_pa, PAGE)
    print(
        "COMPUTE exact timeline publishing native CL2; queue=%s channel=%s "
        "published=%s" % (
            queue.indices(), backend.channels.counters(entry), published),
        flush=True,
    )
    exact.trigger_submission(front, backend, "work", "CL_2")

    after = before
    deadline = time.monotonic() + 0.010
    while time.monotonic() < deadline:
        after = exact.physical_read(backend, output_pa, PAGE)
        if after != before:
            break
        time.sleep(0.0001)
    print(
        "COMPUTE exact timeline result queue=%s channel=%s output=%s" % (
            queue.indices(), backend.channels.counters(entry),
            "changed" if after != before else "unchanged"),
        flush=True,
    )
    if after == before:
        print("COMPUTE OUTPUT: unchanged", flush=True)
        return 2

    changed = sum(left != right for left, right in zip(before, after))
    print(
        "COMPUTE OUTPUT: EXECUTED, native client page changed %d bytes; "
        "captured-post-image=%s" % (
            changed,
            "match" if after == native["expected_output"] else "different"),
        flush=True,
    )
    return 0


