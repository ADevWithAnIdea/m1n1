def build_clear_compiler_pages():
    """Build the complete static compiler closure for one clear."""
    pages = {}
    for dva, offset, body in CLEAR_COMPILER_PRODUCTS:
        if dva in pages or offset + len(body) > PAGE_SIZE:
            raise ValueError("invalid G17G clear compiler product")
        page = bytearray(PAGE_SIZE)
        page[offset:offset + len(body)] = body
        page = bytes(page)
        expected = _SPARSE_CLEAR_COMPILER_PAGE_SHA256.get(
            dva, CLEAR_COMPILER_PAGE_SHA256[dva]
        )
        if hashlib.sha256(page).hexdigest() != expected:
            raise ValueError("G17G clear compiler product hash mismatch")
        pages[dva] = page
    complete_pages = dict(_COMPLETE_CLEAR_COMPILER_PAGES_B85)
    complete_pages[0x10000008000] = (
        _COMPLETE_CLEAR_COMPILER_CONTINUATION_PAGE_B85
    )
    for dva, encoded in complete_pages.items():
        page = zlib.decompress(base64.b85decode(encoded))
        if (
            len(page) != PAGE_SIZE
            or hashlib.sha256(page).hexdigest()
            != CLEAR_COMPILER_PAGE_SHA256[dva]
        ):
            raise ValueError("G17G complete clear compiler page hash mismatch")
        pages[dva] = page
    return pages
