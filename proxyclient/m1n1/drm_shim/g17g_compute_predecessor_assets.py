def build_compute_predecessor_caller_pages():
    """Return the complete fixed caller pages needed at first admission."""
    pages = {}
    for dva, encoded in _COMPUTE_PREDECESSOR_CALLER_PAGES_B85.items():
        page = zlib.decompress(base64.b85decode(encoded))
        if (
            len(page) != PAGE_SIZE
            or hashlib.sha256(page).hexdigest()
            != COMPUTE_PREDECESSOR_CALLER_PAGE_SHA256[dva]
        ):
            raise ValueError("G17G compute-predecessor caller asset changed")
        pages[dva] = page
    return dict(sorted(pages.items()))


def compute_predecessor_shader_tail():
    """Return the bounded companion-program tail after the add kernel."""
    tail = zlib.decompress(
        base64.b85decode(_COMPUTE_PREDECESSOR_SHADER_TAIL_B85)
    )
    if (
        len(tail)
        != COMPUTE_PREDECESSOR_SHADER_TAIL_END
        - COMPUTE_PREDECESSOR_SHADER_TAIL_OFFSET
        or hashlib.sha256(tail).hexdigest()
        != COMPUTE_PREDECESSOR_SHADER_TAIL_SHA256
    ):
        raise ValueError("G17G compute-predecessor shader tail changed")
    return tail
